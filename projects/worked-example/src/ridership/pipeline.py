"""The whole analysis, end to end. ``run`` returns every number the report uses."""
import json
from pathlib import Path

import numpy as np

from sklearn.linear_model import LinearRegression

from ridership import analysis, model, plots, report
from ridership.clean import clean_rides
from ridership.features import add_calendar_features, add_rain_flag
from ridership.load import load_rides


def run(input_path, output_dir, make_figures: bool = True) -> dict:
    """Load, clean, analyse, model and report.

    Args:
        input_path: Path to the raw ``daily_rides.csv``.
        output_dir: Project root; results go to ``data/processed`` and ``reports``.
        make_figures: Set False to skip saving charts (used by fast tests).

    Returns:
        A dictionary of results (also written to ``reports/results.json`` and summarised in ``reports/results.md``).
    """
    output_dir = Path(output_dir)
    raw = load_rides(input_path)
    df = add_rain_flag(add_calendar_features(clean_rides(raw)))

    processed = output_dir / "data" / "processed" / "rides_clean.csv"
    processed.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(processed, index=False)

    results = {"n_raw": len(raw), "n_missing_temp": int(df["temp_was_missing"].sum())}
    results["describe"] = analysis.describe_rides(df)
    results["weekend"] = analysis.compare_weekend(df)
    results["temp_corr"] = analysis.correlation_with_ci(df["temp_c"], df["rides"])
    results["rain_raw_r"] = float(df["rain_mm"].corr(df["rides"]))

    ols = analysis.fit_demand_model(df)
    coefs = analysis.coefficient_table(ols)
    results["coefficients"] = coefs.to_dict(orient="index")
    results["r2"] = float(ols.rsquared)

    # Does the filled-in temperature matter? Refit without the imputed days.
    observed_only = df[~df["temp_was_missing"]]
    results["sensitivity_temp_coef"] = float(analysis.fit_demand_model(observed_only).params["temp_c"])

    train, test = model.chronological_split(df, n_test=60)
    eval_df = model.evaluate_models(train, test)
    cv_df = model.time_series_cv_rmse(df)
    results["model_eval"] = eval_df.round(3).to_dict(orient="index")
    results["model_cv"] = cv_df.round(3).to_dict(orient="index")

    slope = float(coefs.loc["temp_c", "coef"])
    simple_slope = float(np.polyfit(df["temp_c"], df["rides"], 1)[0])
    sentences = {
        "describe": report.describe_sentence(results["describe"]),
        "weekend": report.weekend_sentence(results["weekend"]),
        "temperature": report.temperature_sentence(results["temp_corr"], simple_slope),
        "model": report.model_sentence(coefs, results["rain_raw_r"]),
        "prediction": report.prediction_sentence(eval_df, cv_df, len(test)),
    }
    results["sentences"] = sentences
    results["adjusted_temp_slope"] = slope

    reports = output_dir / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    (reports / "results.json").write_text(json.dumps(results, indent=2, default=str))
    (reports / "results.md").write_text(
        "# Results (generated by run_analysis.py)\n\n" + "\n\n".join(f"**{k.title()}.** {v}" for k, v in sentences.items()) + "\n"
    )

    if make_figures:
        fig_dir = reports / "figures"
        lin = LinearRegression().fit(train[model.FEATURES], train["rides"])
        plots.save_figure(plots.plot_monthly_rides(df), fig_dir / "monthly_rides.png")
        plots.save_figure(plots.plot_weekend_vs_weekday(df), fig_dir / "weekend_vs_weekday.png")
        plots.save_figure(plots.plot_temperature_vs_rides(df, results["temp_corr"]["r"]), fig_dir / "temperature_vs_rides.png")
        plots.save_figure(plots.plot_rain_effect(df, float(coefs.loc["rain_mm", "coef"])), fig_dir / "rain_effect.png")
        plots.save_figure(
            plots.plot_test_predictions(test, lin.predict(test[model.FEATURES]), eval_df.loc["linear regression", "rmse"]),
            fig_dir / "test_predictions.png",
        )
    return results
